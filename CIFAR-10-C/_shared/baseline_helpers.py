def atomic_write_json(path: Path, payload: dict[str, object]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    ) as handle:
        temporary_path = Path(handle.name)
        json.dump(payload, handle, indent=2, sort_keys=True)
        handle.write("\n")
    os.replace(temporary_path, path)


def atomic_savez(path: Path, **arrays: np.ndarray) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            dir=path.parent,
            prefix=f".{path.name}.",
            suffix=".npz",
            delete=False,
        ) as handle:
            temporary_path = Path(handle.name)
        np.savez_compressed(temporary_path, **arrays)
        os.replace(temporary_path, path)
    finally:
        if temporary_path is not None and temporary_path.exists():
            temporary_path.unlink()


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while block := handle.read(1024 * 1024):
            digest.update(block)
    return digest.hexdigest()


def resolve_data_dir(path: Path) -> Path:
    path = path.expanduser().resolve()
    candidates = (path, path / "CIFAR-10-C")
    for candidate in candidates:
        if (candidate / "labels.npy").is_file():
            return candidate
    raise FileNotFoundError(
        f"Could not find extracted labels.npy under {path}. Extract the archive first, "
        f"for example: tar -xf {path / 'CIFAR-10-C.tar'} -C {path}"
    )


def load_split_indices(split_path: Path) -> tuple[np.ndarray, np.ndarray]:
    if not split_path.is_file():
        raise FileNotFoundError(f"Split file not found: {split_path}")
    with np.load(split_path, allow_pickle=False) as split_file:
        required = {"train", "val", "test"}
        missing = required.difference(split_file.files)
        if missing:
            raise ValueError(f"Split file is missing arrays: {sorted(missing)}")
        source_indices = np.sort(
            np.concatenate(
                (
                    np.asarray(split_file["train"], dtype=np.int64),
                    np.asarray(split_file["val"], dtype=np.int64),
                )
            )
        )
        test_indices = np.asarray(split_file["test"], dtype=np.int64)
    if np.intersect1d(source_indices, test_indices).size:
        raise ValueError("Source train+validation and test indices overlap")
    return source_indices, test_indices


def validate_dataset(
    data_dir: Path,
    labels: np.ndarray,
    source_indices: np.ndarray,
    test_indices: np.ndarray,
) -> tuple[int, int]:
    expected_files = [data_dir / f"{name}.npy" for name in CORRUPTIONS]
    missing = [str(path) for path in expected_files if not path.is_file()]
    if missing:
        raise FileNotFoundError(
            "Missing extracted corruption arrays:\n  " + "\n  ".join(missing)
        )
    if labels.ndim != 1:
        raise ValueError(f"Expected one-dimensional labels, got shape {labels.shape}")
    if labels.size == 0:
        raise ValueError("labels.npy is empty")
    all_indices = np.concatenate((source_indices, test_indices))
    if all_indices.min() < 0 or all_indices.max() >= labels.shape[0]:
        raise IndexError("Split indices fall outside labels.npy")

    sample = np.load(expected_files[0], mmap_mode="r", allow_pickle=False)
    if sample.ndim != 4 or sample.shape[0] != labels.shape[0]:
        raise ValueError(
            f"Expected corruption shape ({labels.shape[0]}, H, W, C), got {sample.shape}"
        )
    feature_count = int(np.prod(sample.shape[1:]))
    return labels.shape[0], feature_count


def resolve_embedding_cache(path: Path, row_count: int) -> tuple[Path, int, str]:
    root = path.expanduser().resolve()
    metadata_path = root / "metadata.json"
    if not metadata_path.is_file():
        raise FileNotFoundError(f"Embedding-cache metadata not found: {metadata_path}")
    with metadata_path.open("r", encoding="utf-8") as handle:
        metadata = json.load(handle)
    dimension = int(metadata.get("embedding_dimension", 0))
    if dimension <= 0:
        raise ValueError(f"Invalid embedding_dimension in {metadata_path}")
    for environment in CORRUPTIONS:
        path = root / f"{environment}.npy"
        if not path.is_file():
            raise FileNotFoundError(f"Embedding cache is missing {path}")
        embeddings = np.load(path, mmap_mode="r", allow_pickle=False)
        if embeddings.shape != (row_count, dimension) or embeddings.dtype != np.float32:
            raise ValueError(
                f"Invalid embedding cache {path}: expected ({row_count}, {dimension}) "
                f"float32, got {embeddings.shape} {embeddings.dtype}"
            )
    return root, dimension, sha256(metadata_path)


def iter_index_batches(
    indices: np.ndarray,
    batch_size: int,
    minimum_final_batch: int = 1,
) -> Iterator[np.ndarray]:
    if batch_size < minimum_final_batch:
        raise ValueError(
            f"batch size {batch_size} must be at least {minimum_final_batch}"
        )
    start = 0
    while len(indices) - start > batch_size:
        stop = start + batch_size
        if len(indices) - stop < minimum_final_batch:
            break
        yield indices[start:stop]
        start = stop
    if start < len(indices):
        yield indices[start:]


def load_flat_batch(images: np.ndarray, indices: np.ndarray) -> np.ndarray:
    batch = np.asarray(images[indices], dtype=np.float32)
    return batch.reshape(batch.shape[0], -1) / INPUT_SCALE


def load_source_matrix(
    data_dir: Path,
    source_environments: Sequence[str],
    source_indices: np.ndarray,
    feature_count: int,
    batch_size: int,
) -> np.ndarray:
    total_rows = len(source_environments) * len(source_indices)
    size_gib = total_rows * feature_count * np.dtype(np.float32).itemsize / 2**30
    print(
        f"Allocating source matrix shape=({total_rows}, {feature_count}) "
        f"dtype=float32 size={size_gib:.2f} GiB",
        flush=True,
    )
    try:
        source_matrix = np.empty((total_rows, feature_count), dtype=np.float32)
    except MemoryError as exc:
        raise MemoryError(
            f"Could not allocate the {size_gib:.2f} GiB source matrix. "
            "Request more job memory or use a smaller dataset."
        ) from exc

    started = time.perf_counter()
    destination_start = 0
    for environment_index, environment in enumerate(source_environments, start=1):
        environment_started = time.perf_counter()
        images = np.load(
            data_dir / f"{environment}.npy", mmap_mode="r", allow_pickle=False
        )
        for indices in iter_index_batches(source_indices, batch_size):
            destination_stop = destination_start + len(indices)
            destination = source_matrix[destination_start:destination_stop]
            destination[:] = np.asarray(images[indices]).reshape(len(indices), -1)
            destination *= 1.0 / INPUT_SCALE
            destination_start = destination_stop
        print(
            f"Loaded source [{environment_index}/{len(source_environments)}] "
            f"environment={environment} "
            f"elapsed={time.perf_counter() - environment_started:.1f}s",
            flush=True,
        )

    print(
        f"Loaded all source rows into RAM in {time.perf_counter() - started:.1f}s",
        flush=True,
    )
    return source_matrix


def load_source_embeddings(
    embedding_root: Path,
    source_environments: Sequence[str],
    source_indices: np.ndarray,
    embedding_dimension: int,
    batch_size: int,
) -> np.ndarray:
    total_rows = len(source_environments) * len(source_indices)
    result = np.empty((total_rows, embedding_dimension), dtype=np.float32)
    destination_start = 0
    started = time.perf_counter()
    for environment_index, environment in enumerate(source_environments, start=1):
        embeddings = np.load(embedding_root / f"{environment}.npy", mmap_mode="r", allow_pickle=False)
        for indices in iter_index_batches(source_indices, batch_size):
            destination_stop = destination_start + len(indices)
            result[destination_start:destination_stop] = embeddings[indices]
            destination_start = destination_stop
        print(
            f"Loaded embeddings [{environment_index}/{len(source_environments)}] "
            f"environment={environment}", flush=True,
        )
    print(f"Loaded source embeddings in {time.perf_counter() - started:.1f}s", flush=True)
    return result


def fit_pca(
    source_matrix: np.ndarray,
    n_components: int,
    iterated_power: int,
    seed: int,
) -> tuple[PCA, np.ndarray]:
    if n_components <= 0:
        raise ValueError("--n-components must be positive")
    if iterated_power < 0:
        raise ValueError("--pca-iterated-power must be non-negative")
    pca = PCA(
        n_components=n_components,
        svd_solver="randomized",
        iterated_power=iterated_power,
        random_state=seed,
        copy=True,
    )
    started = time.perf_counter()
    embeddings = pca.fit_transform(source_matrix)
    print(
        f"Randomized PCA fit completed in {time.perf_counter() - started:.1f}s; "
        f"embedding shape={embeddings.shape}",
        flush=True,
    )
    return pca, embeddings


def save_pca(
    path: Path,
    pca: PCA,
    target: str,
    source_environments: Sequence[str],
    split_hash: str,
    iterated_power: int,
    seed: int,
) -> None:
    atomic_savez(
        path,
        components=np.asarray(pca.components_),
        mean=np.asarray(pca.mean_),
        explained_variance=np.asarray(pca.explained_variance_),
        explained_variance_ratio=np.asarray(pca.explained_variance_ratio_),
        singular_values=np.asarray(pca.singular_values_),
        n_samples_seen=np.asarray([pca.n_samples_], dtype=np.int64),
        input_scale=np.asarray([INPUT_SCALE], dtype=np.float64),
        solver=np.asarray("randomized"),
        iterated_power=np.asarray([iterated_power], dtype=np.int64),
        seed=np.asarray([seed], dtype=np.int64),
        target=np.asarray(target),
        source_environments=np.asarray(source_environments),
        split_sha256=np.asarray(split_hash),
    )


def load_pca(
    path: Path,
    target: str,
    source_environments: Sequence[str],
    split_hash: str,
    n_components: int,
    iterated_power: int,
    seed: int,
) -> tuple[np.ndarray, np.ndarray]:
    with np.load(path, allow_pickle=False) as artifact:
        components = np.asarray(artifact["components"])
        mean = np.asarray(artifact["mean"])
        checks = {
            "target": str(artifact["target"]),
            "source_environments": tuple(artifact["source_environments"].tolist()),
            "split_sha256": str(artifact["split_sha256"]),
            "solver": str(artifact["solver"]),
            "iterated_power": int(artifact["iterated_power"][0]),
            "seed": int(artifact["seed"][0]),
            "input_scale": float(artifact["input_scale"][0]),
        }
    expected = {
        "target": target,
        "source_environments": tuple(source_environments),
        "split_sha256": split_hash,
        "solver": "randomized",
        "iterated_power": iterated_power,
        "seed": seed,
        "input_scale": INPUT_SCALE,
    }
    if checks != expected or components.shape[0] != n_components:
        raise ValueError(
            f"PCA cache metadata mismatch at {path}. "
            "Use --refit-pca to replace it."
        )
    if components.ndim != 2 or mean.shape != (components.shape[1],):
        raise ValueError(f"Invalid PCA shapes in {path}")
    return components, mean


def transform(
    images: np.ndarray,
    indices: np.ndarray,
    components: np.ndarray,
    mean: np.ndarray,
) -> np.ndarray:
    flattened = load_flat_batch(images, indices)
    return (flattened - mean) @ components.T


def binary_targets(labels: np.ndarray, class_ids: np.ndarray) -> np.ndarray:
    return np.where(labels[:, None] == class_ids[None, :], 1.0, -1.0)


def transform_source_matrix(
    source_matrix: np.ndarray,
    components: np.ndarray,
    mean: np.ndarray,
    batch_size: int,
) -> np.ndarray:
    embeddings = np.empty(
        (source_matrix.shape[0], components.shape[0]), dtype=np.float32
    )
    started = time.perf_counter()
    for start in range(0, source_matrix.shape[0], batch_size):
        stop = min(start + batch_size, source_matrix.shape[0])
        embeddings[start:stop] = (source_matrix[start:stop] - mean) @ components.T
    print(
        f"Transformed cached PCA embeddings in {time.perf_counter() - started:.1f}s; "
        f"embedding shape={embeddings.shape}",
        flush=True,
    )
    return embeddings


def fit_linear_models(
    embeddings: np.ndarray,
    source_labels: np.ndarray,
    class_ids: np.ndarray,
    batch_size: int,
) -> tuple[np.ndarray, np.ndarray, int, int, float | None]:
    if embeddings.shape[0] != source_labels.shape[0]:
        raise ValueError("Source embeddings and labels have different row counts")
    augmented_dim = embeddings.shape[1] + 1
    xtx = np.zeros((augmented_dim, augmented_dim), dtype=np.float64)
    xty = np.zeros((augmented_dim, len(class_ids)), dtype=np.float64)
    yty = np.zeros(len(class_ids), dtype=np.float64)
    rows_seen = 0

    started = time.perf_counter()
    for start in range(0, embeddings.shape[0], batch_size):
        stop = min(start + batch_size, embeddings.shape[0])
        design = np.empty((stop - start, augmented_dim), dtype=np.float64)
        design[:, :-1] = embeddings[start:stop]
        design[:, -1] = 1.0
        targets = binary_targets(source_labels[start:stop], class_ids)
        xtx += design.T @ design
        xty += design.T @ targets
        yty += np.square(targets).sum(axis=0)
        rows_seen += stop - start

    weights, _residuals, rank, singular_values = np.linalg.lstsq(
        xtx, xty, rcond=None
    )
    fitted_sse = yty - 2.0 * np.sum(weights * xty, axis=0)
    fitted_sse += np.sum(weights * (xtx @ weights), axis=0)
    source_mse = np.maximum(fitted_sse, 0.0) / rows_seen
    condition_number = (
        float(singular_values[0] / singular_values[-1])
        if singular_values[-1] > 0.0
        else None
    )
    print(
        f"Linear regression fit completed in {time.perf_counter() - started:.1f}s",
        flush=True,
    )
    return weights, source_mse, rows_seen, int(rank), condition_number


def evaluate_target(
    target_path: Path,
    test_indices: np.ndarray,
    labels: np.ndarray,
    class_ids: np.ndarray,
    weights: np.ndarray,
    components: np.ndarray,
    mean: np.ndarray,
    batch_size: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    images = np.load(target_path, mmap_mode="r", allow_pickle=False)
    scores: list[np.ndarray] = []
    targets: list[np.ndarray] = []
    for indices in iter_index_batches(test_indices, batch_size):
        embeddings = transform(images, indices, components, mean)
        batch_scores = embeddings @ weights[:-1] + weights[-1]
        scores.append(batch_scores)
        targets.append(binary_targets(labels[indices], class_ids))

    all_scores = np.concatenate(scores, axis=0)
    all_targets = np.concatenate(targets, axis=0)
    mse = np.mean(np.square(all_scores - all_targets), axis=0)
    auroc = np.asarray(
        [
            roc_auc_score(all_targets[:, index] == 1.0, all_scores[:, index])
            for index in range(len(class_ids))
        ],
        dtype=np.float64,
    )
    return all_scores, all_targets, mse, auroc


def evaluate_target_embeddings(
    target_path: Path,
    test_indices: np.ndarray,
    labels: np.ndarray,
    class_ids: np.ndarray,
    weights: np.ndarray,
    batch_size: int,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    embeddings = np.load(target_path, mmap_mode="r", allow_pickle=False)
    scores: list[np.ndarray] = []
    targets: list[np.ndarray] = []
    for indices in iter_index_batches(test_indices, batch_size):
        batch_scores = np.asarray(embeddings[indices], dtype=np.float32) @ weights[:-1] + weights[-1]
        scores.append(batch_scores)
        targets.append(binary_targets(labels[indices], class_ids))
    all_scores = np.concatenate(scores, axis=0)
    all_targets = np.concatenate(targets, axis=0)
    mse = np.mean(np.square(all_scores - all_targets), axis=0)
    auroc = np.asarray([
        roc_auc_score(all_targets[:, index] == 1.0, all_scores[:, index])
        for index in range(len(class_ids))
    ], dtype=np.float64)
    return all_scores, all_targets, mse, auroc


def link_or_copy(source: Path, destination: Path) -> None:
    destination.parent.mkdir(parents=True, exist_ok=True)
    temporary = destination.with_name(f".{destination.name}.tmp")
    if temporary.exists():
        temporary.unlink()
    try:
        os.link(source, temporary)
    except OSError:
        shutil.copy2(source, temporary)
    os.replace(temporary, destination)


def is_complete(run_dir: Path, expected_config: dict[str, object]) -> bool:
    config_path = run_dir / "config.json"
    required = (
        config_path,
        run_dir / "metrics.json",
        run_dir / "linear_model.npz",
        run_dir / "target_test_predictions.npz",
    )
    representation_artifact = (
        run_dir / "representation_metadata.json"
        if expected_config.get("representation_mode") == "frozen_embedding_cache"
        else run_dir / "pca.npz"
    )
    if not all(path.is_file() for path in (*required, representation_artifact)):
        return False
    try:
        with config_path.open("r", encoding="utf-8") as handle:
            config = json.load(handle)
        return config.get("status") == "complete" and all(
            config.get(key) == value for key, value in expected_config.items()
        )
    except (OSError, json.JSONDecodeError):
        return False


def main() -> None:
    args = parse_args()
    if args.batch_size <= 0:
        raise ValueError("--batch-size must be positive")
    if args.pca_iterated_power < 0:
        raise ValueError("--pca-iterated-power must be non-negative")

    requested_tasks = list(dict.fromkeys(args.tasks or CLASS_NAMES))
    output_root = args.output_root.expanduser().resolve()
    split_path = args.split_file.expanduser().resolve()
    embedding_root: Path | None = None
    embedding_dimension: int | None = None
    embedding_metadata_hash: str | None = None
    if args.embedding_root is not None:
        candidate_root = args.embedding_root.expanduser().resolve()
        metadata_path = candidate_root / "metadata.json"
        if not metadata_path.is_file():
            raise FileNotFoundError(f"Embedding-cache metadata not found: {metadata_path}")
        with metadata_path.open("r", encoding="utf-8") as handle:
            embedding_dimension = int(json.load(handle).get("embedding_dimension", 0))
        if embedding_dimension <= 0:
            raise ValueError(f"Invalid embedding_dimension in {metadata_path}")
        embedding_root = candidate_root
        embedding_metadata_hash = sha256(metadata_path)
    run_dirs = {
        task: output_root / f"{task}_vs_rest" / args.target
        for task in requested_tasks
    }
    expected_completed_config: dict[str, object] = {
        "target_environment": args.target,
        "split_file": str(split_path),
        "batch_size": args.batch_size,
    }
    if embedding_root is None:
        expected_completed_config.update({
            "representation_mode": "pca",
            "n_components": args.n_components,
            "pca_method": "sklearn.decomposition.PCA(randomized)",
            "pca_iterated_power": args.pca_iterated_power,
            "seed": args.seed,
            "input_scale": INPUT_SCALE,
        })
    else:
        expected_completed_config.update({
            "representation_mode": "frozen_embedding_cache",
            "embedding_root": str(embedding_root),
            "embedding_dimension": embedding_dimension,
            "embedding_metadata_sha256": embedding_metadata_hash,
        })
    tasks = [
        task
        for task in requested_tasks
        if args.force
        or args.refit_pca
        or not is_complete(run_dirs[task], expected_completed_config)
    ]
    if not tasks:
        print(f"All requested tasks are already complete for target={args.target}")
        return

    data_dir = resolve_data_dir(args.data_dir)
    source_indices, test_indices = load_split_indices(split_path)
    labels = np.load(data_dir / "labels.npy", mmap_mode="r", allow_pickle=False)
    row_count, feature_count = validate_dataset(
        data_dir, labels, source_indices, test_indices
    )
    if embedding_root is None and args.n_components > feature_count:
        raise ValueError(
            f"--n-components={args.n_components} exceeds {feature_count} pixel features"
        )

    source_environments = tuple(
        environment for environment in CORRUPTIONS if environment != args.target
    )
    split_hash = sha256(split_path)
    pca_cache = (
        output_root
        / "_pca_by_target"
        / args.target
        / (
            f"pca_{args.n_components}_randomized_"
            f"power_{args.pca_iterated_power}_seed_{args.seed}.npz"
        )
    )

    if embedding_root is not None:
        embedding_root, embedding_dimension, embedding_metadata_hash = resolve_embedding_cache(
            embedding_root, row_count
        )
        source_embeddings = load_source_embeddings(
            embedding_root, source_environments, source_indices,
            embedding_dimension, args.batch_size,
        )
        components = mean = None
    else:
        source_matrix = load_source_matrix(
            data_dir, source_environments, source_indices, feature_count, args.batch_size,
        )
        if pca_cache.is_file() and not args.refit_pca:
            print(f"Loading PCA cache: {pca_cache}", flush=True)
            components, mean = load_pca(
                pca_cache, args.target, source_environments, split_hash,
                args.n_components, args.pca_iterated_power, args.seed,
            )
            source_embeddings = transform_source_matrix(source_matrix, components, mean, args.batch_size)
        else:
            print(f"Fitting {args.n_components}-component randomized PCA on {len(source_environments)} source environments in RAM", flush=True)
            fitted_pca, source_embeddings = fit_pca(source_matrix, args.n_components, args.pca_iterated_power, args.seed)
            save_pca(pca_cache, fitted_pca, args.target, source_environments, split_hash, args.pca_iterated_power, args.seed)
            components = np.asarray(fitted_pca.components_)
            mean = np.asarray(fitted_pca.mean_)
        del source_matrix

    class_ids = np.asarray([CLASS_NAMES.index(task) for task in tasks], dtype=np.int64)
    base_config: dict[str, object] = {
        "status": "running",
        "target_environment": args.target,
        "source_environments": list(source_environments),
        "source_splits": ["train", "val"],
        "evaluation_split": "test",
        "data_dir": str(data_dir),
        "split_file": str(split_path),
        "split_sha256": split_hash,
        "batch_size": args.batch_size,
        "regression": "unregularized ordinary least squares with intercept",
        "row_count_per_environment": row_count,
        "source_train_val_rows_per_environment": int(len(source_indices)),
        "target_test_rows": int(len(test_indices)),
    }
    if embedding_root is None:
        base_config.update({
            "representation_mode": "pca", "n_components": args.n_components,
            "pca_iterated_power": args.pca_iterated_power, "seed": args.seed,
            "input_scale": INPUT_SCALE, "pca_method": "sklearn.decomposition.PCA(randomized)",
        })
    else:
        base_config.update({
            "representation_mode": "frozen_embedding_cache", "embedding_root": str(embedding_root),
            "embedding_dimension": embedding_dimension, "embedding_metadata_sha256": embedding_metadata_hash,
        })
    for task, class_id in zip(tasks, class_ids, strict=True):
        run_dir = run_dirs[task]
        run_dir.mkdir(parents=True, exist_ok=True)
        config = dict(base_config, task=f"{task}_vs_rest", positive_class_id=int(class_id))
        atomic_write_json(run_dir / "config.json", config)
        if embedding_root is None:
            link_or_copy(pca_cache, run_dir / "pca.npz")
        else:
            link_or_copy(embedding_root / "metadata.json", run_dir / "representation_metadata.json")

    source_labels = np.tile(
        np.asarray(labels[source_indices], dtype=np.int64), len(source_environments)
    )
    weights, source_mse, source_rows, rank, condition_number = fit_linear_models(
        source_embeddings,
        source_labels,
        class_ids,
        args.batch_size,
    )
    del source_embeddings, source_labels
    if embedding_root is None:
        scores, targets, test_mse, test_auroc = evaluate_target(
            data_dir / f"{args.target}.npy", test_indices, labels, class_ids,
            weights, components, mean, args.batch_size,
        )
    else:
        scores, targets, test_mse, test_auroc = evaluate_target_embeddings(
            embedding_root / f"{args.target}.npy", test_indices, labels,
            class_ids, weights, args.batch_size,
        )

    for task_index, (task, class_id) in enumerate(
        zip(tasks, class_ids, strict=True)
    ):
        run_dir = run_dirs[task]
        atomic_savez(
            run_dir / "linear_model.npz",
            coefficients=weights[:-1, task_index],
            intercept=np.asarray([weights[-1, task_index]]),
            positive_class_id=np.asarray([class_id], dtype=np.int64),
            positive_class_name=np.asarray(task),
        )
        atomic_savez(
            run_dir / "target_test_predictions.npz",
            indices=test_indices,
            targets=targets[:, task_index],
            scores=scores[:, task_index],
        )
        metrics: dict[str, object] = {
            "task": f"{task}_vs_rest",
            "positive_class_id": int(class_id),
            "target_environment": args.target,
            "source_train_val_count": source_rows,
            "target_test_count": int(len(test_indices)),
            "target_test_positive_count": int(
                np.count_nonzero(targets[:, task_index] == 1.0)
            ),
            "source_train_val_mse": float(source_mse[task_index]),
            "target_test_mse": float(test_mse[task_index]),
            "target_test_auroc": float(test_auroc[task_index]),
            "normal_equation_rank": rank,
            "normal_equation_condition_number": condition_number,
        }
        atomic_write_json(run_dir / "metrics.json", metrics)
        with (run_dir / "config.json").open("r", encoding="utf-8") as handle:
            completed_config = json.load(handle)
        completed_config["status"] = "complete"
        completed_config["artifacts"] = {
            "linear_model": "linear_model.npz",
            "target_test_predictions": "target_test_predictions.npz",
            "metrics": "metrics.json",
        }
        completed_config["artifacts"]["representation"] = (
            "pca.npz" if embedding_root is None else "representation_metadata.json"
        )
        atomic_write_json(run_dir / "config.json", completed_config)
        print(
            f"Completed task={task}_vs_rest target={args.target}: "
            f"MSE={test_mse[task_index]:.6f} AUROC={test_auroc[task_index]:.6f}",
            flush=True,
        )


if __name__ == "__main__":
    main()
